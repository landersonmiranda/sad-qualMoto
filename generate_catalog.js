// Helper to calculate realistic secondary parameters based on price and category
function makeMoto({
  id,
  fipeCode,
  name,
  brand,
  category,
  price,
  cityKml,
  highwayKml,
  depreciation = 0.07,
  comfortScore = 4.0,
  performanceScore = 4.0,
  reliabilityScore = 4.5,
  resaleLiquidityScore = 4.3,
  badge
}) {
  const isElectric = category === 'eletrica';
  const monthlyFinancing = Math.round(price * 0.026);
  const ipvaRate = isElectric ? 0.00 : 0.02;
  const licensingAnnual = 160;
  
  // Insurance roughly 7% - 9% of price per year, capped reasonably
  const insuranceAnnual = Math.round(Math.max(750, Math.min(12000, price * 0.082)));
  
  // Maintenance per km
  let maintenancePerKm = 0.12;
  if (isElectric) maintenancePerKm = 0.05;
  else if (price < 15000) maintenancePerKm = 0.08;
  else if (price < 25000) maintenancePerKm = 0.13;
  else if (price < 40000) maintenancePerKm = 0.19;
  else if (price < 70000) maintenancePerKm = 0.28;
  else if (price < 120000) maintenancePerKm = 0.38;
  else maintenancePerKm = 0.50;

  return {
    id,
    fipeCode: fipeCode || `fipe-${id}`,
    name,
    brand,
    category,
    year: 2024,
    price,
    monthlyFinancing,
    fipeDepreciationYearly: depreciation,
    cityKml,
    highwayKml,
    ipvaRate,
    licensingAnnual,
    insuranceAnnual,
    maintenancePerKm,
    comfortScore,
    performanceScore,
    reliabilityScore,
    resaleLiquidityScore,
    badge: badge || `${brand} ${category.toUpperCase()}`
  };
}

